"""Builds report.pdf from model/metrics.json and screenshots/. Run: python docs/build_report.py"""
import json
from pathlib import Path
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (Image, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle)

ROOT = Path(__file__).resolve().parent.parent
m = json.loads((ROOT / "model" / "metrics.json").read_text())
ss = getSampleStyleSheet()
H1 = ParagraphStyle("H1", parent=ss["Heading1"], fontSize=14, spaceBefore=10, spaceAfter=4, keepWithNext=1, textColor=colors.HexColor("#1f3a5f"))
B = ParagraphStyle("B", parent=ss["BodyText"], fontSize=10, leading=14)
SM = ParagraphStyle("SM", parent=B, fontSize=8.5, leading=11)
story = []

def h(t): story.append(Paragraph(t, H1))
def p(t): story.append(Paragraph(t, B)); story.append(Spacer(1, 4))
def bullets(items): [story.append(Paragraph("&bull; " + i, B)) for i in items]; story.append(Spacer(1, 4))
def img(name, w=13):
    from PIL import Image as PI
    path = ROOT / "screenshots" / name
    iw, ih = PI.open(path).size
    story.append(Image(str(path), width=w * cm, height=w * cm * ih / iw)); story.append(Spacer(1, 6))
def table(data, widths=None, fs=8.5):
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f3a5f")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), fs), ("GRID", (0, 0), (-1, -1), 0.4, colors.grey), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f2f5f9")])]))
    story.append(t); story.append(Spacer(1, 8))

story.append(Paragraph("Customer Support Ticket Classification - Solution Report", ss["Title"]))
story.append(Paragraph("AI Fresher Technical Assignment", ss["Heading3"]))

h("A. Problem Understanding")
p("A company receives support tickets through email, chat and other channels. Reading and sorting each ticket by hand is slow. "
  "The goal is to build a basic machine-learning system that learns from historical tickets and predicts the <b>category</b> of a new "
  "ticket using only its text description. This is a <b>multi-class text classification</b> problem with 5 classes.")

h("B. Dataset")
bullets(["<b>Source:</b> self-created synthetic dataset (no external dataset, so no URL). Generated by <font face='Courier'>data/generate_dataset.py</font> "
         "from hand-written phrase pools, with random greetings/closing phrases for variety, plus 20 deliberately ambiguous tickets.",
         "<b>Records:</b> 226 raw rows (218 after cleaning).  <b>Categories:</b> 5 - Login Issue, Application Error, Report, Account Update, Performance.",
         "<b>Fields:</b> ticket_id, ticket_description, category, priority, status.",
         "<b>Modification note:</b> 6 duplicate descriptions, 2 blank descriptions, a few missing priority/status values and messy casing "
         "were injected on purpose to demonstrate the cleaning step."])
img("dataset.png", 16)

h("C. Data Preprocessing")
bullets(["<b>Missing values:</b> rows with no description cannot be classified, so 2 were dropped. Missing priority/status (not used by the model) were filled with 'Unknown' instead of losing data.",
         "<b>Duplicates:</b> removed after text cleaning (so 'Hi, forgot password!' and 'hi forgot password' count as the same). 6 removed. This also prevents the same ticket appearing in both train and test sets.",
         "<b>Text cleaning:</b> lowercase, remove punctuation/digits, collapse extra spaces. Stop-words were deliberately kept because words like 'not', 'cannot', 'unable' are meaningful in support tickets.",
         "<b>Why:</b> models see different strings for 'Password' and 'password!'. Cleaning reduces such noise and keeps the vocabulary small, which matters with a small dataset."])

h("Exploratory Data Analysis")
p("The 218 cleaned tickets are almost perfectly balanced across the 5 categories (42-45 each), so accuracy is a fair metric and no re-sampling is needed. "
  "Priority and status are spread across Medium/High/Low and Closed/Open/In Progress. Priority differs by category: Application Error and Login tickets are "
  "mostly High, while Account Update and Report tickets are mostly Medium/Low. Descriptions are short (about 12 words on average), which is why simple word features work reasonably.")
img("analysis_category.png", 11); img("analysis_priority.png", 11)

h("D. Model Selection")
p("<b>Pipeline:</b> Ticket text &rarr; cleaning &rarr; TF-IDF (1- and 2-word sequences) &rarr; Logistic Regression &rarr; predicted category + confidence.")
bullets(["<b>Features:</b> TF-IDF gives each word/word-pair a weight that is high when it is frequent in a ticket but rare across all tickets (e.g. 'password', 'slow'), and low for common words.",
         "<b>Algorithm:</b> Logistic Regression learns one weight per feature per category; the category with the highest probability (softmax) is the prediction.",
         "<b>Why:</b> simple, fast, works well on small text datasets, easy to explain (we can list the top words per category), and gives probabilities for the 'Confidence' score.",
         "<b>Comparison:</b> Naive Bayes, Logistic Regression and Linear SVM were compared with 5-fold cross-validation on the training set only:"])
cv = [["Model", "CV accuracy (mean +/- std)"]] + [[k, f"{v['mean']:.3f} +/- {v['std']:.3f}"] for k, v in m["cv_accuracy"].items()]
table(cv, [6 * cm, 6 * cm])
p("The three models are within one standard deviation of each other, so the difference is not meaningful. Logistic Regression was chosen for its probabilities and interpretability, not because it won by a large margin.")

h("E. Training and Testing")
bullets([f"<b>Split:</b> 80% train ({m['train_size']} tickets) / 20% test ({m['test_size']} tickets), stratified so every category keeps its proportion, random_state=42.",
         "<b>Training:</b> the TF-IDF vocabulary and the classifier weights are learned from the training data only (no information leaks from the test set).",
         "<b>Testing:</b> the saved model predicts the unseen test tickets once; predictions are compared with the true categories."])

h("F. Results")
table([["Metric", "Value"], ["Accuracy", f"{m['test_accuracy']:.1%}"], ["Precision (weighted)", f"{m['test_precision_weighted']:.1%}"],
       ["Recall (weighted)", f"{m['test_recall_weighted']:.1%}"], ["F1 score (weighted)", f"{m['test_f1_weighted']:.1%}"]], [6 * cm, 4 * cm], 9)
img("confusion_matrix.png", 9)
wrong = m["misclassified"]
p(f"<b>In simple words:</b> the model correctly classified about {m['test_accuracy']:.0%} of the test tickets ({m['test_size'] - len(wrong)} of {m['test_size']}). "
  "Rows of the confusion matrix are the true categories and columns are the predictions; the diagonal is correct predictions.")
p("<b>The " + str(len(wrong)) + " mistakes</b> were both ambiguous tickets that mix two topics: " +
  "; ".join(f"'{w['text']}' (true: {w['actual']}, predicted: {w['predicted']})" for w in wrong) +
  ". These tickets contain words from two categories, so the error is understandable.")
p("<b>Is it satisfactory?</b> For a first prototype, yes. <b>However</b>, the dataset is synthetic and built from repeating phrase patterns, and the test set has only 44 tickets "
  "(one mistake = 2.3 points). So 95% is an optimistic estimate; on real, messier tickets I would expect lower accuracy and would need to re-measure.")

h("G. Prediction on New Tickets")
p("Ten new tickets, written separately from the training data (checked for no overlap), were tested:")
img("prediction.png", 16)
p("All 10 were correct, but a few had low confidence (e.g. 31% for 'Software crashed and I lost my work'), showing the model is unsure on wording it has not seen. "
  "The apps flag confidence below 50% for manual review.")

h("Bonus: Suggested Response")
p("A rule-based reply per category (<font face='Courier'>src/responses.py</font>) is shown after prediction in both the CLI and the web app. No external API is used, so there are no keys.")

h("H. Limitations")
bullets(["<b>Synthetic, small dataset</b> (218 tickets) written by one person: real customers use far more varied wording, typos, and other languages.",
         "<b>Tiny test set</b> (44): the accuracy estimate has wide uncertainty.",
         "<b>Ambiguous tickets</b> that mention two issues are assigned a single category; the model cannot output multiple labels.",
         "<b>Bag-of-words features</b> ignore word order and meaning; unseen words (out-of-vocabulary) are ignored.",
         "<b>Only 5 categories</b>; an unrelated ticket (e.g. billing) will still be forced into one of them.",
         "Confidence scores from Logistic Regression are not guaranteed to be well calibrated."])

h("I. Future Improvements")
bullets(["Train on real historical tickets (thousands), reviewed by support staff; add more categories including an 'Other' class.",
         "Better preprocessing: spelling correction, lemmatization, handling multilingual text.",
         "Better models: sentence embeddings (e.g. SBERT) or a fine-tuned transformer; compare with LLM-based classification.",
         "Human-in-the-loop: send low-confidence tickets to an agent and use their corrections for periodic retraining.",
         "Production: REST API (FastAPI), database storage, monitoring for data drift, model versioning.",
         "Allow multi-label prediction and use priority/status/metadata as extra features."])

h("Libraries and AI-tool usage")
p("Libraries: pandas, NumPy, scikit-learn, Matplotlib, Seaborn, joblib, Flask, ReportLab. "
  "<b>AI tools:</b> Claude (Anthropic) was used to help scaffold the code and draft this report; I ran, reviewed and can explain all of the implementation. "
  "No API keys or credentials are included.")

SimpleDocTemplate(str(ROOT / "report.pdf"), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=1.8 * cm, bottomMargin=1.8 * cm,
                  title="Customer Support Ticket Classification - Report").build(story)
print("report.pdf built")
